# ---------------------------------------------------------------------------
# Helper: load a module by path without putting it on sys.path
# ---------------------------------------------------------------------------
def _load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


# ---------------------------------------------------------------------------
# Base test class with shared assertions
# ---------------------------------------------------------------------------
class _BaseTests:
    """Mixin of test cases that run against any engine/discourse pair."""

    def test_classical_logic_syllogism(self):
        """Demo 1: All men are mortal; Socrates is a man -> Socrates is mortal."""
        self.engine.facts.clear()
        self.engine.rules.clear()
        self.engine.load_program("""
man(socrates).
man(plato).
mortal(X) :- man(X).
""")
        sol = self.engine.query("mortal(socrates)")
        self.assertTrue(sol, "Socrates should be mortal")

        sol_all = self.engine.query("mortal(X)")
        names = {s.get("X") for s in sol_all}
        self.assertIn("socrates", names)
        self.assertIn("plato", names)

    def test_family_relationships(self):
        """Demo 2: grandparent reasoning."""
        self.engine.facts.clear()
        self.engine.rules.clear()
        self.engine.load_program("""
parent(john, mary).
parent(mary, bob).
male(john).
grandparent(X, Z) :- parent(X, Y), parent(Y, Z).
""")
        sol = self.engine.query("grandparent(X, bob)")
        names = {s.get("X") for s in sol}
        self.assertIn("john", names)

    def test_expert_system_diagnosis(self):
        """Demo 3: MYCIN-like diagnosis."""
        self.engine.facts.clear()
        self.engine.rules.clear()
        self.engine.load_program("""
symptom(patient1, fever).
symptom(patient1, cough).
diagnosis(flu, X) :- symptom(X, fever), symptom(X, cough).
diagnosis(cold, X) :- symptom(X, cough).
""")
        sol = self.engine.query("diagnosis(D, patient1)")
        diseases = {s.get("D") for s in sol}
        self.assertIn("flu", diseases)
        self.assertIn("cold", diseases)

    def test_planning_prerequisites(self):
        """Demo 4: task scheduling with before/2."""
        self.engine.facts.clear()
        self.engine.rules.clear()
        self.engine.load_program("""
before(foundation, walls).
before(walls, roof).
before(roof, painting).
direct_prereq(A, B) :- before(A, B).
two_step_prereq(A, C) :- before(A, B), before(B, C).
""")
        sol1 = self.engine.query("direct_prereq(X, painting)")
        names1 = {s.get("X") for s in sol1}
        self.assertIn("roof", names1)

        sol2 = self.engine.query("two_step_prereq(X, painting)")
        names2 = {s.get("X") for s in sol2}
        self.assertIn("walls", names2)

    def test_complete_loop(self):
        """Demo 5: end-to-end neuro-symbolic loop via Discourse.

        Uses a query the regex layer can fully resolve (parent/2 facts
        are generated by interpret, and the query is parent/2).
        """
        self.engine.facts.clear()
        self.engine.rules.clear()
        trace = self.discourse.loop(
            "John is the parent of Mary. Mary is the parent of Bob. Who is the parent of Bob?",
            domain="family"
        )
        self.assertIn("solutions", trace)
        self.assertTrue(trace["solutions"], "Should find a parent")
        names = {s.get("X") for s in trace["solutions"]}
        self.assertIn("mary", names)

    def test_loop_converges_early(self):
        """The Revise loop stops early when the knowledge base converges."""
        self.engine.facts.clear()
        self.engine.rules.clear()
        trace = self.discourse.loop(
            "John is the parent of Mary. Mary is the parent of Bob. Who is the parent of Bob?",
            domain="family",
            max_iterations=5
        )
        # Iteration 1: domain-specific facts.
        # Iteration 2: broader interpretation finds new (noisy) facts.
        # Iteration 3: no new facts -> converges.
        self.assertLess(len(trace["iterations"]), 5,
                        "Loop should converge before max_iterations")
        self.assertIn("solutions", trace)
        names = {s.get("X") for s in trace["solutions"]}
        self.assertIn("mary", names)

    def test_discourse_interpret_family(self):
        """Discourse interprets a family statement into Prolog syntax."""
        result = self.discourse.interpret("John is the father of Mary.", domain="family")
        # Regex layer returns parent(john, mary); Ollama may return father(john, mary)
        self.assertTrue(
            any("john" in r and "mary" in r for r in result),
            f"Expected john/mary relation in {result}"
        )

    def test_discourse_interpret_logic(self):
        """Discourse interprets a classical-logic statement."""
        result = self.discourse.interpret("Socrates is a man.", domain="classical_logic")
        self.assertTrue(any("man(socrates)" in r for r in result),
                        f"Expected man(socrates) in {result}")


