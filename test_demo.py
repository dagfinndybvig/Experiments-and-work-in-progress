        if result.returncode != 0 and "pyswip" in result.stderr:
            self.skipTest("pyswip/SWI-Prolog not installed")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("NEURO-SYMBOLIC AI DEMONSTRATION", result.stdout)


