# ---------------------------------------------------------------------------
# Tests for the SWI-Prolog backend (skip if pyswip / SWI-Prolog missing)
# ---------------------------------------------------------------------------
class TestPrologBackend(unittest.TestCase, _BaseTests):
    @classmethod
    def setUpClass(cls):
        try:
            cls.mod = _load_module("neuro_symbolic_demo_prolog", "neuro_symbolic_demo_prolog.py")
        except Exception as exc:
            raise unittest.SkipTest(f"SWI-Prolog backend not available: {exc}")
        cls.engine = cls.mod.PrologEngine()
        cls.discourse = cls.mod.LLMDiscourse(cls.engine)

    def test_real_prolog_recursion(self):
        """Demo 6: unbounded recursion and lists (toy engine cannot do this)."""
        self.engine.facts.clear()
        self.engine.rules.clear()
        self.engine.load_program("""
parent(john, mary).
parent(mary, bob).
parent(bob, alice).
ancestor(X, Y) :- parent(X, Y).
ancestor(X, Z) :- parent(X, Y), ancestor(Y, Z).
member(X, [X|_]).
member(X, [_|T]) :- member(X, T).
""")
        sol = self.engine.query("ancestor(X, alice)")
        names = {s.get("X") for s in sol}
        self.assertIn("john", names)
        self.assertIn("mary", names)
        self.assertIn("bob", names)

        self.assertTrue(self.engine.query("member(3, [1,2,3,4])"))
        sol_list = self.engine.query("member(X, [a,b,c])")
        self.assertEqual(len(sol_list), 3)


# ---------------------------------------------------------------------------
# Tests for the Ollama-backed Discourse (skip if Ollama not running)
# ---------------------------------------------------------------------------
class TestOllamaBackend(unittest.TestCase, _BaseTests):
    @classmethod
    def setUpClass(cls):
        # First check whether Ollama is reachable
        try:
            result = subprocess.run(
                [sys.executable, "neuro_symbolic_demo_ollama.py", "--status"],
                capture_output=True, text=True, timeout=10
            )
        except Exception as exc:
            raise unittest.SkipTest(f"Could not check Ollama status: {exc}")
        if "Ollama UP" not in result.stdout:
            raise unittest.SkipTest("Ollama is not running; skipping Ollama tests.")

        try:
            cls.mod = _load_module("neuro_symbolic_demo_ollama", "neuro_symbolic_demo_ollama.py")
        except Exception as exc:
            raise unittest.SkipTest(f"Ollama module import failed: {exc}")
        cls.engine = cls.mod.PrologEngine()
        cls.discourse = cls.mod.OllamaDiscourse(cls.engine)


